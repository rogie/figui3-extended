import type { PropsKitConfig } from "@rogieking/figui3/propskit.js";
import {
  CSS_PROPERTY_MODULES,
  createCssModuleConfig,
  type CssPropertyModuleId,
} from "../../../css-properties.js";
import type { PropsKitSection } from "./propskitSections";

export function sourceForModule(
  id: CssPropertyModuleId,
  label: string,
  element?: Element,
): string {
  void element;
  return `import {
  figCreateModule
} from "@rogieking/figui3-extended/css-properties.js"

// ${label}
const module = figCreateModule(${JSON.stringify(id)})
module.mount("#properties")`;
}

export const moduleSections: PropsKitSection[] = CSS_PROPERTY_MODULES.filter(
  (module) => module.id !== "mask",
).map((module) => ({
    id: `module-${module.id}`,
    name: module.label,
    description: `${module.label} CSS properties with friendly labels and controls generated by PropsKit.`,
    group: "Modules",
    examples: [
      {
        id: "default",
        name: "Default",
        title: `${module.label} properties`,
        panelName: module.label,
        cssModuleId: module.id,
        description: `An unconstrained ${module.label.toLowerCase()} module. Associate an element to filter properties and seed values from its current computed style.`,
        markup: sourceForModule(module.id, module.label),
        createConfig: () =>
          createCssModuleConfig(module.id).config as PropsKitConfig,
      },
    ],
  }));
