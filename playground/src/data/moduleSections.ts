import type { PropsKitConfig } from "@rogieking/figui3/propskit.js";
import {
  CSS_PROPERTY_MODULES,
  createCssModuleConfig,
  type CssPropertyModuleId,
} from "../../../css-properties.js";
import type { PropsKitSection } from "./propskitSections";

export function sourceForModule(
  id: CssPropertyModuleId,
  label: string,
  element?: Element,
): string {
  void element;
  return `import {
  figCreateModule
} from "@rogieking/figui3-extended/css-properties.js"

// ${label}
const module = figCreateModule(${JSON.stringify(id)})
module.mount("#properties")`;
}

const ALL_MODULE_IDS: CssPropertyModuleId[] = [
  "layout",
  "appearance",
  "typography",
  "transforms",
  "background",
  "border",
  "outline",
  "stroke",
  "filters",
];

const allModulesSource = `import {
  figCreateModule
} from "@rogieking/figui3-extended/css-properties.js"

const properties = document.querySelector("#properties")
const mount = id => figCreateModule(id).mount(properties)
const append = tag => properties.append(document.createElement(tag))

mount("layout")
mount("appearance")
mount("typography")
append("fig-module-transforms")
append("fig-module-fills")
mount("border")
mount("outline")
mount("stroke")
append("fig-module-filters")`;

const allModulesSection: PropsKitSection = {
  id: "module-all",
  name: "All",
  description:
    "Layout, appearance, typography, transforms, fills, border, outline, stroke, and filters in one module stack.",
  group: "Modules",
  examples: [
    {
      id: "default",
      name: "Default",
      title: "All modules",
      panelName: "All",
      description:
        "All primary visual property modules mounted together in their standard order.",
      markup: allModulesSource,
      createConfig: () =>
        Object.assign(
          {},
          ...ALL_MODULE_IDS.map(
            (id) => createCssModuleConfig(id).config as PropsKitConfig,
          ),
        ),
    },
  ],
};

export const moduleSections: PropsKitSection[] = [
  allModulesSection,
  ...CSS_PROPERTY_MODULES.filter(
    (module) => module.id !== "mask",
  ).map((module) => ({
      id: `module-${module.id}`,
      name: module.label,
      description: `${module.label} CSS properties with friendly labels and controls generated by PropsKit.`,
      group: "Modules",
      examples: [
        {
          id: "default",
          name: "Default",
          title: `${module.label} properties`,
          panelName: module.label,
          cssModuleId: module.id,
          description: `An unconstrained ${module.label.toLowerCase()} module. Associate an element to filter properties and seed values from its current computed style.`,
          markup: sourceForModule(module.id, module.label),
          createConfig: () =>
            createCssModuleConfig(module.id).config as PropsKitConfig,
        },
      ],
    })),
];
